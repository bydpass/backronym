  var TABLES = { zh: ZH, en: EN }, PREF_KEY = "backronym-ui-lang";

  // 界面语言：设置页选的（只存本机）优先；没选就跟随环境语言——中文环境用中文，其余用英文，读不到时用中文。
  // ponytail: 容器有没有把小红书 app 的语言交给小工具还没在真机核实，现在读的是 navigator.language
  function pref() { try { var v = root.localStorage && root.localStorage.getItem(PREF_KEY); return v === "zh" || v === "en" ? v : "auto"; } catch (e) { return "auto"; } }
  function detect() { var nav = root.navigator, l = nav && (nav.language || (nav.languages && nav.languages[0])) || ""; return !l || /^zh\b/i.test(l) ? "zh" : "en"; }
  function setPref(v) { try { if (v === "zh" || v === "en") root.localStorage.setItem(PREF_KEY, v); else root.localStorage.removeItem(PREF_KEY); } catch (e) { /* 存不了就只管这一次 */ } }
  var lang = pref(); if (lang === "auto") lang = detect();

  // 取一条文案。占位只替换一遍：填进去的内容（用户的词、配文）里即使有大括号也不会再被当成占位。
  // 编号写错时原样返回编号，不让界面因为一条字出错停下；编号是否都在表里由 scripts/test-i18n.mjs 把关
  function t(id, params) {
    var table = TABLES[lang] || ZH, s = Object.prototype.hasOwnProperty.call(table, id) ? table[id] : ZH[id];
    if (typeof s !== "string") return String(id);
    if (s.indexOf("[[") >= 0) s = s.replace(/\[\[([^|\]]*)\|([^\]]*)\]\]/g, function (m, one, other) { return params && Number(params.n) === 1 ? one : other; });
    if (!params) return s;
    return s.replace(/\{([A-Za-z]+)\}/g, function (m, k) { return Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m; });
  }

  // 把页面里带编号的静态文字换成当前语言。中文界面不用换（页面本来就写着中文）
  function apply(doc) {
    if (lang === "zh" || !doc || !doc.querySelectorAll) return;
    var i, k, list, el, n, pairs, at;
    doc.documentElement.lang = lang;
    for (list = doc.querySelectorAll("[data-i18n-html]"), i = 0; i < list.length; i++) list[i].innerHTML = t(list[i].getAttribute("data-i18n-html"));
    for (list = doc.querySelectorAll("[data-i18n]"), i = 0; i < list.length; i++) {
      for (el = list[i], n = el.firstChild; n; n = n.nextSibling) if (n.nodeType === 3 && /\S/.test(n.nodeValue)) { n.nodeValue = n.nodeValue.replace(/^(\s*)[\s\S]*?(\s*)$/, function (m, a, z) { return a + t(el.getAttribute("data-i18n")) + z; }); break; }
    }
    for (list = doc.querySelectorAll("[data-i18n-attrs]"), i = 0; i < list.length; i++) {
      for (pairs = list[i].getAttribute("data-i18n-attrs").split(";"), k = 0; k < pairs.length; k++) { at = pairs[k].indexOf(":"); list[i].setAttribute(pairs[k].slice(0, at), t(pairs[k].slice(at + 1))); }
    }
  }

  var api = { t: t, tables: TABLES, lang: function () { return lang; }, pref: pref, setPref: setPref, apply: apply };
  if (typeof module === "object" && module.exports) module.exports = api; else { root.I18N = api; apply(root.document); }
